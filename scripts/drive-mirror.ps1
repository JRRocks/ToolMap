# Mirrors the local ToolMap folder to Google Drive (second backup) and
# publishes the compiled debug APK to "APK release" as ToolMap.<version>.apk.
# Needs Google Drive for desktop (the Drive is mounted as a local drive).
#
#   powershell -ExecutionPolicy Bypass -File scripts\drive-mirror.ps1
#   powershell -ExecutionPolicy Bypass -File scripts\drive-mirror.ps1 -DriveRoot "G:\Mon Drive"

param(
    [string]$DriveRoot = "",
    [switch]$SkipApk
)

$ErrorActionPreference = "Stop"
$projectDir = Split-Path -Parent $PSScriptRoot

if (-not $DriveRoot) {
    $candidates = Get-PSDrive -PSProvider FileSystem | ForEach-Object {
        Join-Path $_.Root "Mon Drive"
        Join-Path $_.Root "My Drive"
    }
    $DriveRoot = $candidates | Where-Object { Test-Path (Join-Path $_ "2 - Jean") } | Select-Object -First 1
    if (-not $DriveRoot) {
        throw "Google Drive introuvable : installer Google Drive pour ordinateur ou passer -DriveRoot."
    }
}

$claudeCode = Join-Path $DriveRoot "2 - Jean\Claude Code"
$mirrorDir = Join-Path $claudeCode "ToolMap"
$apkDir = Join-Path $claudeCode "APK release"
New-Item -ItemType Directory -Force $mirrorDir, $apkDir | Out-Null

# Never overwrite a newer copy with an older one (CLAUDE.md, "Copie la plus récente d'abord").
function Get-ToolMapVersion([string]$dir) {
    $file = Join-Path $dir "version.properties"
    if (-not (Test-Path $file)) { return $null }
    $value = [regex]::Match((Get-Content $file -Raw), '(?m)^version=(\S+)').Groups[1].Value
    if ($value) { [version]$value } else { $null }
}
$localVersion = Get-ToolMapVersion $projectDir
$driveVersion = Get-ToolMapVersion $mirrorDir
if ($driveVersion -and $localVersion -and $driveVersion -gt $localVersion) {
    throw "Le Drive ($driveVersion) est plus récent que le local ($localVersion) : mettre le local à jour d'abord."
}

# Source files only: build outputs and caches are regenerated by Gradle.
# /MIR also deletes on the Drive what was deleted locally (the Drive is a mirror).
robocopy $projectDir $mirrorDir /MIR /FFT /R:2 /W:5 /NP /NDL `
    /XD .git build .gradle .kotlin .idea .cxx captures `
    /XF local.properties *.apk *.aab | Out-Host
if ($LASTEXITCODE -ge 8) { throw "robocopy a échoué (code $LASTEXITCODE)" }

if (-not $SkipApk) {
    # The version of the last local build (version.properties, ADR-059).
    $props = Get-Content (Join-Path $projectDir "version.properties") -Raw
    $version = [regex]::Match($props, '(?m)^version=(\S+)').Groups[1].Value
    $apk = Join-Path $projectDir "app\build\outputs\apk\debug\ToolMap-debug-$version.apk"
    if (Test-Path $apk) {
        $target = Join-Path $apkDir "ToolMap.$version.apk"
        Copy-Item $apk $target -Force
        Write-Host "APK publié : $target"
    } else {
        Write-Warning "APK absent ($apk) : lancer ./gradlew assembleDebug d'abord."
    }
}
exit 0
