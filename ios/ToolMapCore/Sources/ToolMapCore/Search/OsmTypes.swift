    /// The name to show for `type`; nil for none.
    public static func french(_ type: String?) -> String? {
        let key = type.map { kotlinTrim($0).lowercased() } ?? ""
        if key.isEmpty { return nil }
        if let name = names[key] { return name }
        let spaced = String(key.map { $0 == "_" ? " " : $0 })
        guard let first = spaced.first else { return spaced }
        return first.uppercased() + String(spaced.dropFirst())
    }
