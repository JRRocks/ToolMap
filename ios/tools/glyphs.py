#!/usr/bin/env python3
"""Writes ios/ToolMapCore/Sources/ToolMapCore/Resources/glyphs.json from the vector drawables of the Android app.

Usage (from anywhere, Python 3, no dependency):
    python3 ios/tools/glyphs.py           # (re)writes glyphs.json
    python3 ios/tools/glyphs.py --check   # exit status 1 when glyphs.json is not up to date

The iPhone app draws the same icons as Android without reading Android's files at build time (ADR-100): this script
copies their outlines once, and glyphs.json is committed. Run it again whenever tools/icons/generate.mjs regenerates
the drawables or a token is added.

Sources (app/src/main/res/drawable/), and where the icons come from (ADR-050, ADR-056):
  ic_wp_<id>.xml    -> "wp_<id>"     waypoint icons (WaypointCatalog.Icon.id), generated by tools/icons/generate.mjs
  ic_act_<id>.xml   -> "act_<id>"    activity icons (TrackActivity, lower case), generated by tools/icons/generate.mjs
  ic_token_<id>.xml -> "token_<id>"  share tokens (MemberLook.icons)
  - Maki (Mapbox, @mapbox/maki): CC0 1.0, public domain;
  - Temaki (Rapid Editor, @rapideditor/temaki): CC0 1.0, public domain;
  - Material Design Icons (Pictogrammers, @mdi/svg): Apache License 2.0;
  - game-icons.net (share tokens: Lorc, Delapouite and the other authors listed on game-icons.net): CC BY 3.0, which
    asks for the credit shown in the app's help screen.
The first line comment of each drawable names its source icon.

Output: one JSON object, keys sorted, one glyph per line:
  {"wp_peak": {"w": 15, "h": 15, "paths": [{"d": "M7.5,1...", "evenOdd": false}]}, ...}
"w" and "h" are the viewport (y counted downwards, as in SVG and Android); each path is filled on its own, with the
non-zero rule unless "evenOdd". Whitespace inside the path data is collapsed; nothing else is changed.
"""

import json
import pathlib
import re
import sys
import xml.etree.ElementTree as ElementTree

ROOT = pathlib.Path(__file__).resolve().parents[2]
DRAWABLES = ROOT / "app" / "src" / "main" / "res" / "drawable"
OUTPUT = ROOT / "ios" / "ToolMapCore" / "Sources" / "ToolMapCore" / "Resources" / "glyphs.json"
FAMILIES = (("ic_wp_", "wp_"), ("ic_act_", "act_"), ("ic_token_", "token_"))
ANDROID = "{http://schemas.android.com/apk/res/android}"

# Only what the generated drawables use: filled paths, no group, no stroke, no transparency.
SUPPORTED_VECTOR = {"width", "height", "viewportWidth", "viewportHeight"}
SUPPORTED_PATH = {"fillColor", "fillType", "pathData"}

# The tokens of SVG path data, as VectorPath.swift reads them (flags of arcs aside: a number covers them here).
TOKEN = re.compile(r"[ \t\n\r\f,]*(?:([MmLlHhVvCcSsQqTtAaZz])|([-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?))")
ARGUMENTS = {"m": 2, "l": 2, "h": 1, "v": 1, "c": 6, "s": 4, "q": 4, "t": 2, "a": 7, "z": 0}


def number(text):
    value = float(text)
    return int(value) if value.is_integer() else value


def check_path(data, where):
    """Fails on path data VectorPath.swift would refuse: unknown characters, a wrong count of numbers."""
    segments = []
    position = 0
    while position < len(data):
        match = TOKEN.match(data, position)
        if not match:
            if data[position:].strip(" \t\n\r\f,"):
                raise SystemExit(f"{where}: unexpected path data at {position}: {data[position:position + 20]!r}")
            break
        position = match.end()
        if match.group(1):
            segments.append([match.group(1), 0])
        elif not segments:
            raise SystemExit(f"{where}: number before any command")
        else:
            segments[-1][1] += 1
    if segments and segments[0][0] not in "Mm":
        raise SystemExit(f"{where}: path data must start with a moveto")
    for command, count in segments:
        size = ARGUMENTS[command.lower()]
        if (count != 0) if size == 0 else (count == 0 or count % size != 0):
            raise SystemExit(f"{where}: {count} numbers after {command!r}")


def read_drawable(path):
    root = ElementTree.parse(path).getroot()
    if root.tag != "vector":
        raise SystemExit(f"{path.name}: not a <vector>")
    attributes = {key.removeprefix(ANDROID): value for key, value in root.attrib.items()}
    unknown = set(attributes) - SUPPORTED_VECTOR
    if unknown:
        raise SystemExit(f"{path.name}: unsupported attributes {sorted(unknown)}")
    paths = []
    for child in root:
        if child.tag != "path":
            raise SystemExit(f"{path.name}: unsupported element <{child.tag}>")
        attributes = {key.removeprefix(ANDROID): value for key, value in child.attrib.items()}
        unknown = set(attributes) - SUPPORTED_PATH
        if unknown:
            raise SystemExit(f"{path.name}: unsupported path attributes {sorted(unknown)}")
        data = " ".join(attributes["pathData"].split())
        check_path(data, path.name)
        paths.append({"d": data, "evenOdd": attributes.get("fillType", "nonZero") == "evenOdd"})
    if not paths:
        raise SystemExit(f"{path.name}: no path")
    width = number(root.get(ANDROID + "viewportWidth"))
    height = number(root.get(ANDROID + "viewportHeight"))
    return {"w": width, "h": height, "paths": paths}


def build():
    glyphs = {}
    for prefix, key_prefix in FAMILIES:
        files = sorted(DRAWABLES.glob(prefix + "*.xml"))
        if not files:
            raise SystemExit(f"no {prefix}*.xml in {DRAWABLES}")
        for path in files:
            glyphs[key_prefix + path.stem.removeprefix(prefix)] = read_drawable(path)
    lines = [f"{json.dumps(key)}: {json.dumps(glyphs[key], ensure_ascii=False)}" for key in sorted(glyphs)]
    return "{\n" + ",\n".join(lines) + "\n}\n", glyphs


def main():
    text, glyphs = build()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is not up to date: run python3 ios/tools/glyphs.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date ({len(glyphs)} glyphs)")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    counts = {key_prefix: sum(1 for key in glyphs if key.startswith(key_prefix)) for _, key_prefix in FAMILIES}
    summary = ", ".join(f"{count} {key_prefix}*" for key_prefix, count in counts.items())
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(glyphs)} glyphs ({summary}), {len(text.encode())} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
