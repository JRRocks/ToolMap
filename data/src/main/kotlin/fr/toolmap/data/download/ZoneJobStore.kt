package fr.toolmap.data.download

import fr.toolmap.core.download.ZoneJob
import fr.toolmap.core.download.ZoneJobCodec
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import java.io.File

/** Zone download jobs, one JSON file each in [dir]; survives app restarts so a download can be resumed. */
class ZoneJobStore(
    private val dir: File,
) {
    private val flow = MutableStateFlow(readAll())

    /** Newest first. */
    val jobs: StateFlow<List<ZoneJob>> = flow.asStateFlow()

    fun get(id: String): ZoneJob? = flow.value.firstOrNull { it.request.id == id }

    @Synchronized
    fun save(job: ZoneJob) {
        dir.mkdirs()
        val file = fileFor(job.request.id)
        val temp = File(dir, file.name + ".tmp")
        temp.writeText(ZoneJobCodec.encode(job), Charsets.UTF_8)
        if (!temp.renameTo(file)) {
            file.delete()
            check(temp.renameTo(file)) { "Cannot write ${file.name}" }
        }
        flow.value = (flow.value.filterNot { it.request.id == job.request.id } + job).sortedByDescending { order(it) }
    }

    @Synchronized
    fun delete(id: String) {
        fileFor(id).delete()
        flow.value = flow.value.filterNot { it.request.id == id }
    }

    private fun readAll(): List<ZoneJob> =
        dir
            .listFiles { f -> f.isFile && f.name.endsWith(SUFFIX) }
            .orEmpty()
            .mapNotNull { runCatching { ZoneJobCodec.decodeOrNull(it.readText(Charsets.UTF_8)) }.getOrNull() }
            .sortedByDescending { order(it) }

    private fun order(job: ZoneJob) = job.request.createdAtMillis

    // Job ids are generated by the app, but never trust them as file names.
    private fun fileFor(id: String) = File(dir, id.filter { it.isLetterOrDigit() || it == '-' || it == '_' } + SUFFIX)

    private companion object {
        const val SUFFIX = ".json"
    }
}
