// Generates the waypoint icon set from tools/icons/catalog.txt (P16.6, ADR-051).
//
// Usage:  node tools/icons/generate.mjs <dir with the extracted npm packages>
//   <dir>/mapbox-maki-*/package/icons/*.svg           (@mapbox/maki, CC0-1.0)
//   <dir>/rapideditor-temaki-*/package/icons/*.svg    (@rapideditor/temaki, CC0-1.0)
//   <dir>/mdi-svg-*/package/svg/*.svg                 (@mdi/svg, Apache-2.0)
// Get them with:  npm pack @mapbox/maki @rapideditor/temaki @mdi/svg   then extract each .tgz in its own folder.
//
// Writes: app/src/main/res/drawable/ic_wp_*.xml, app/src/main/res/values/strings_waypoint_icons.xml,
//         app/src/main/kotlin/fr/toolmap/waypoints/WaypointIconRes.kt and
//         core/src/main/kotlin/fr/toolmap/core/track/WaypointCatalog.kt.
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..', '..')
const src = process.argv[2]
if (!src) {
  console.error('usage: node tools/icons/generate.mjs <dir with extracted maki, temaki and mdi packages>')
  process.exit(1)
}
const dirOf = (prefix, sub) => {
  const d = fs.readdirSync(src).find((n) => n.startsWith(prefix) && fs.statSync(path.join(src, n)).isDirectory())
  if (!d) throw new Error('missing package ' + prefix)
  return path.join(src, d, 'package', sub)
}
const dirs = { maki: dirOf('mapbox-maki', 'icons'), temaki: dirOf('rapideditor-temaki', 'icons'), mdi: dirOf('mdi-svg', 'svg') }

const categories = []
const icons = []
const aliases = []
const activities = []
let inActivities = false
for (const raw of fs.readFileSync(path.join(root, 'tools/icons/catalog.txt'), 'utf8').split(/\r?\n/)) {
  const line = raw.trim()
  if (!line || line.startsWith('#')) continue
  if (line === '@activities') {
    inActivities = true
  } else if (inActivities) {
    const [id, label, source, color] = line.split('|')
    activities.push({ id, label, source, color })
  } else if (line.startsWith('@cat|')) {
    const [, id, label, color] = line.split('|')
    categories.push({ id, label, color })
  } else if (line.startsWith('~')) {
    const [key, target] = line.slice(1).split('|')
    aliases.push({ key, target })
  } else {
    const [id, key, label, source, color] = line.split('|')
    icons.push({ id, key, label, source, color: color || categories[categories.length - 1].color, cat: categories[categories.length - 1].id })
  }
}

const num = (v) => (v === undefined ? undefined : parseFloat(v))
function attrs(tag) {
  const out = {}
  for (const m of tag.matchAll(/([a-zA-Z:-]+)\s*=\s*"([^"]*)"/g)) out[m[1]] = m[2]
  return out
}
function circlePath(cx, cy, r) {
  return `M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0z`
}
function rectPath(x, y, w, h) {
  return `M${x},${y}h${w}v${h}h${-w}z`
}
function parseSvg(text, label) {
  const vb = /viewBox="([^"]+)"/.exec(text)?.[1].split(/[\s,]+/).map(Number) ?? [0, 0, 24, 24]
  const paths = []
  for (const m of text.matchAll(/<(path|circle|rect)\b[^>]*>/g)) {
    const a = attrs(m[0])
    if (a.fill === 'none') continue
    let d
    if (m[1] === 'path') d = a.d
    else if (m[1] === 'circle') d = circlePath(num(a.cx ?? '0'), num(a.cy ?? '0'), num(a.r))
    else d = rectPath(num(a.x ?? '0'), num(a.y ?? '0'), num(a.width), num(a.height))
    if (!d) throw new Error('empty path in ' + label)
    paths.push({ d, evenOdd: a['fill-rule'] === 'evenodd' || a['clip-rule'] === 'evenodd' })
  }
  if (paths.length === 0) throw new Error('no drawable shape in ' + label)
  return { w: vb[2], h: vb[3], paths }
}

const drawableDir = path.join(root, 'app/src/main/res/drawable')
const missing = []
const all = [...icons.map((i) => ({ ...i, drawable: `ic_wp_${i.id}` })), ...activities.map((a) => ({ ...a, drawable: `ic_act_${a.id}` }))]
for (const icon of all) {
  const [set, name] = icon.source.split(':')
  const file = path.join(dirs[set], name + '.svg')
  if (!fs.existsSync(file)) {
    missing.push(`${icon.id} -> ${icon.source}`)
    continue
  }
  const svg = parseSvg(fs.readFileSync(file, 'utf8'), icon.source)
  const body = svg.paths
    .map(
      (p) =>
        `    <path\n        android:fillColor="#FF000000"${p.evenOdd ? '\n        android:fillType="evenOdd"' : ''}\n        android:pathData="${p.d}" />`,
    )
    .join('\n')
  const xml = `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${icon.source} (${set === 'mdi' ? 'Apache-2.0' : 'CC0-1.0'}), generated by tools/icons/generate.mjs -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="${svg.w}"\n    android:viewportHeight="${svg.h}">\n${body}\n</vector>\n`
  fs.writeFileSync(path.join(drawableDir, `${icon.drawable}.xml`), xml)
}
if (missing.length) {
  console.error('MISSING SOURCES:\n' + missing.join('\n'))
  process.exit(2)
}

const xmlEscape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/'/g, "\\'")
let strings = `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/icons/generate.mjs from tools/icons/catalog.txt: do not edit by hand. -->\n<resources>\n`
for (const c of categories) strings += `    <string name="wpcat_${c.id}">${xmlEscape(c.label)}</string>\n`
for (const i of icons) strings += `    <string name="wpicon_${i.id}">${xmlEscape(i.label)}</string>\n`
for (const a of activities) strings += `    <string name="activity_${a.id}">${xmlEscape(a.label)}</string>
`
strings += `</resources>\n`
fs.writeFileSync(path.join(root, 'app/src/main/res/values/strings_waypoint_icons.xml'), strings)

const argb = (hex) => '0xFF' + hex.slice(1).toUpperCase() + '.toInt()'
let res = `// Generated by tools/icons/generate.mjs from tools/icons/catalog.txt: do not edit by hand.\npackage fr.toolmap.waypoints\n\nimport fr.toolmap.R\n\n/** The drawable and the label of every waypoint icon of [fr.toolmap.core.track.WaypointCatalog], by icon id. */\nobject WaypointIconRes {\n    val drawables: Map<String, Int> =\n        mapOf(\n`
for (const i of icons) res += `            "${i.id}" to R.drawable.ic_wp_${i.id},\n`
res += `        )\n\n    val labels: Map<String, Int> =\n        mapOf(\n`
for (const i of icons) res += `            "${i.id}" to R.string.wpicon_${i.id},\n`
res += `        )\n\n    val categoryLabels: Map<String, Int> =\n        mapOf(\n`
for (const c of categories) res += `            "${c.id}" to R.string.wpcat_${c.id},\n`
res += `        )\n}\n`
fs.writeFileSync(path.join(root, 'app/src/main/kotlin/fr/toolmap/waypoints/WaypointIconRes.kt'), res)

let cat = `// Generated by tools/icons/generate.mjs from tools/icons/catalog.txt: do not edit by hand.\npackage fr.toolmap.core.track\n\n/** Every waypoint icon, by category (P16.6). Icon ids are stable; [key] is what is stored and written as the GPX sym. */\nobject WaypointCatalog {\n    class Icon(\n        val id: String,\n        val key: String,\n        val category: String,\n        val colorArgb: Int,\n    )\n\n    class Category(\n        val id: String,\n        val colorArgb: Int,\n        val icons: List<Icon>,\n    )\n\n    val CATEGORIES: List<Category> =\n        listOf(\n`
for (const c of categories) {
  cat += `            Category(\n                "${c.id}",\n                ${argb(c.color)},\n                listOf(\n`
  for (const i of icons.filter((x) => x.cat === c.id))
    cat += `                    Icon("${i.id}", "${i.key.replace(/"/g, '\\"')}", "${c.id}", ${argb(i.color)}),\n`
  cat += `                ),\n            ),\n`
}
cat += `        )\n\n    /** Old Garmin symbol names, still accepted: they point at the equivalent icon id. */\n    val ALIASES: Map<String, String> =\n        mapOf(\n`
for (const a of aliases) cat += `            "${a.key.toLowerCase()}" to "${a.target}",\n`
cat += `        )\n}\n`
fs.writeFileSync(path.join(root, 'core/src/main/kotlin/fr/toolmap/core/track/WaypointCatalog.kt'), cat)
