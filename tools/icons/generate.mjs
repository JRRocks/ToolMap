fs.writeFileSync(path.join(root, 'core/src/main/kotlin/fr/toolmap/core/record/TrackActivity.kt'), en)
console.log(`${icons.length} icons, ${categories.length} categories, ${aliases.length} aliases, ${activities.length} activities`)
